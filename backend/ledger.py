"""
VERITAS — ledger.py

Implements two complementary tamper-evidence mechanisms over EPR certificates:

1.  **Hash chain** — each certificate stores SHA-256(prev_hash || cert_bytes) so that
    any retroactive modification invalidates every entry that follows it.  Verified by
    ``verify_chain``.

2.  **Merkle tree** — certificates are committed to a binary Merkle tree so that a
    single certificate can prove its inclusion in the root hash without revealing the
    full dataset.  Generated by ``build_merkle_tree`` / ``get_merkle_proof`` and
    verified by ``verify_merkle_proof``.

All hash operations use SHA-256 via the stdlib ``hashlib`` module.  No third-party
Merkle library is used; the implementation is written from scratch.
"""

from __future__ import annotations

import hashlib
import sqlite3
from typing import Optional


# ---------------------------------------------------------------------------
# Low-level hash helpers
# ---------------------------------------------------------------------------


def _sha256(data: bytes) -> bytes:
    """Return the 32-byte SHA-256 digest of *data*."""
    return hashlib.sha256(data).digest()


def certificate_bytes(cert: dict[str, object]) -> bytes:
    """Return the canonical UTF-8 byte representation of *cert* for hashing.

    The format is strictly::

        f"{id}|{arrival_id}|{facility_id}|{quantity_kg:.6f}|{waste_category}|{minted_at}"

    All fields are taken directly from the certificate dict (keys: ``id``,
    ``arrival_id``, ``facility_id``, ``quantity_kg``, ``waste_category``,
    ``minted_at``).  Field order and the ``:.6f`` precision on ``quantity_kg``
    are invariant — changing either breaks every stored chain hash.
    """
    canonical = (
        f"{cert['id']}|{cert['arrival_id']}|{cert['facility_id']}"
        f"|{float(cert['quantity_kg']):.6f}"  # type: ignore[arg-type]
        f"|{cert['waste_category']}|{cert['minted_at']}"
    )
    return canonical.encode("utf-8")


def hash_chain_entry(previous_hash: bytes, cert: dict[str, object]) -> bytes:
    """Compute the next hash-chain entry.

    Returns SHA-256(``previous_hash`` || ``certificate_bytes(cert)``).
    The concatenation of the previous hash with the certificate bytes binds each
    entry to its predecessor; tampering with any entry invalidates all successors.
    """
    return _sha256(previous_hash + certificate_bytes(cert))


# ---------------------------------------------------------------------------
# Hash chain — persistence
# ---------------------------------------------------------------------------

_GENESIS_HASH: bytes = b"\x00" * 32


def append_to_chain(
    db: sqlite3.Connection,
    cert_id: str,
) -> str:
    """Compute the new hash-chain entry for *cert_id* and persist it.

    Algorithm:

    1. Fetch the certificate row from the DB.
    2. Find the immediately preceding certificate (by ``minted_at`` ascending,
       then ``id`` as a tiebreaker) and read its ``ledger_hash_hex``.
       If this is the first certificate use the 32-byte genesis hash (all zeros).
    3. Compute ``new_hash = hash_chain_entry(prev_hash_bytes, cert_row)``.
    4. ``UPDATE certificates SET ledger_hash_hex=? WHERE id=?``.
    5. Return the new hash as a lowercase hex string.

    :param db: An open SQLite connection with the VERITAS schema.
    :param cert_id: Primary key of the certificate to append.
    :returns: Hex-encoded 64-character SHA-256 hash string.
    :raises sqlite3.OperationalError: If the certificate is not found.
    """
    db.row_factory = sqlite3.Row
    cur = db.cursor()

    # 1. Fetch the target certificate
    cur.execute(
        "SELECT id, arrival_id, facility_id, quantity_kg, waste_category, minted_at "
        "FROM certificates WHERE id = ?",
        (cert_id,),
    )
    row = cur.fetchone()
    if row is None:
        raise sqlite3.OperationalError(f"Certificate not found: {cert_id!r}")
    cert: dict[str, object] = dict(row)

    # 2. Fetch the previous certificate's hash (ordered by minted_at, then id)
    cur.execute(
        """
        SELECT ledger_hash_hex
        FROM   certificates
        WHERE  (minted_at, id) < (?, ?)
        ORDER  BY minted_at DESC, id DESC
        LIMIT  1
        """,
        (cert["minted_at"], cert_id),
    )
    prev_row = cur.fetchone()

    if prev_row is None or prev_row["ledger_hash_hex"] in ("", None):
        # First certificate ever — use genesis hash
        prev_hash_bytes: bytes = _GENESIS_HASH
    else:
        prev_hash_bytes = bytes.fromhex(str(prev_row["ledger_hash_hex"]))

    # 3. Compute new chain hash
    new_hash = hash_chain_entry(prev_hash_bytes, cert)
    new_hash_hex = new_hash.hex()

    # 4. Persist
    cur.execute(
        "UPDATE certificates SET ledger_hash_hex = ? WHERE id = ?",
        (new_hash_hex, cert_id),
    )
    db.commit()

    return new_hash_hex


def verify_chain(
    db: sqlite3.Connection,
    from_cert_id: Optional[str] = None,
    to_cert_id: Optional[str] = None,
) -> bool:
    """Verify the hash chain is unbroken over the specified range.

    Iterates every certificate in ascending ``(minted_at, id)`` order between
    *from_cert_id* and *to_cert_id* (both inclusive, ``None`` means open-ended).
    For each certificate the expected hash is recomputed from scratch; if the
    stored ``ledger_hash_hex`` does not match, the function returns ``False``
    immediately.

    :param db: An open SQLite connection with the VERITAS schema.
    :param from_cert_id: Start of the range (inclusive); ``None`` = genesis.
    :param to_cert_id: End of the range (inclusive); ``None`` = latest.
    :returns: ``True`` if the entire chain verifies; ``False`` on any mismatch.
    """
    db.row_factory = sqlite3.Row
    cur = db.cursor()

    # Determine minted_at bounds for the requested range
    from_ts: Optional[str] = None
    to_ts: Optional[str] = None

    if from_cert_id is not None:
        cur.execute("SELECT minted_at FROM certificates WHERE id = ?", (from_cert_id,))
        r = cur.fetchone()
        if r is None:
            return False
        from_ts = str(r["minted_at"])

    if to_cert_id is not None:
        cur.execute("SELECT minted_at FROM certificates WHERE id = ?", (to_cert_id,))
        r = cur.fetchone()
        if r is None:
            return False
        to_ts = str(r["minted_at"])

    # Build query — fetch all certs in the range in chronological order
    query = (
        "SELECT id, arrival_id, facility_id, quantity_kg, waste_category, "
        "minted_at, ledger_hash_hex "
        "FROM certificates "
    )
    conditions: list[str] = []
    params: list[str] = []

    if from_ts is not None:
        conditions.append("(minted_at, id) >= (?, ?)")
        params.extend([from_ts, from_cert_id])  # type: ignore[list-item]

    if to_ts is not None:
        conditions.append("(minted_at, id) <= (?, ?)")
        params.extend([to_ts, to_cert_id])  # type: ignore[list-item]

    if conditions:
        query += "WHERE " + " AND ".join(conditions) + " "

    query += "ORDER BY minted_at ASC, id ASC"

    cur.execute(query, params)
    rows = cur.fetchall()

    if not rows:
        # Empty range is vacuously valid
        return True

    # If starting from genesis, previous hash is all-zeros; otherwise we need
    # the hash of the cert immediately before the range.
    if from_cert_id is None:
        running_hash: bytes = _GENESIS_HASH
    else:
        # Find the cert just before the first one in our range
        first = rows[0]
        cur.execute(
            """
            SELECT ledger_hash_hex
            FROM   certificates
            WHERE  (minted_at, id) < (?, ?)
            ORDER  BY minted_at DESC, id DESC
            LIMIT  1
            """,
            (str(first["minted_at"]), str(first["id"])),
        )
        prev = cur.fetchone()
        if prev is None or prev["ledger_hash_hex"] in ("", None):
            running_hash = _GENESIS_HASH
        else:
            running_hash = bytes.fromhex(str(prev["ledger_hash_hex"]))

    for row in rows:
        cert: dict[str, object] = dict(row)
        expected = hash_chain_entry(running_hash, cert)
        stored_hex = str(cert.get("ledger_hash_hex", ""))
        if stored_hex != expected.hex():
            return False
        running_hash = expected

    return True


