# Merkle tree — in-memory
# ---------------------------------------------------------------------------


def build_merkle_tree(leaves: list[bytes]) -> list[list[bytes]]:
    """Build a binary Merkle tree from *leaves* and return all levels.

    The returned list has ``levels[0]`` as the leaf level and
    ``levels[-1]`` as a single-element list containing the root.

    Special cases:

    * **Empty list** — returns ``[[b'\\x00' * 32]]`` (a genesis root).
    * **Odd number of nodes** at any level — the last node is duplicated
      before hashing the pair.

    Internal node hash: SHA-256(left_child || right_child).

    :param leaves: Pre-hashed leaf values (each 32 bytes, but not enforced).
    :returns: List of levels; index 0 = leaf level, last index = root level.
    """
    if not leaves:
        return [[b"\x00" * 32]]

    current_level = list(leaves)
    levels: list[list[bytes]] = [current_level]

    while len(current_level) > 1:
        next_level: list[bytes] = []
        # Duplicate last node if count is odd
        if len(current_level) % 2 == 1:
            current_level = current_level + [current_level[-1]]
        for i in range(0, len(current_level), 2):
            parent = _sha256(current_level[i] + current_level[i + 1])
            next_level.append(parent)
        current_level = next_level
        levels.append(current_level)

    return levels


def get_merkle_root(leaves: list[bytes]) -> bytes:
    """Return the Merkle root bytes for *leaves*.

    :param leaves: Pre-hashed leaf values.
    :returns: 32-byte root hash.
    """
    return build_merkle_tree(leaves)[-1][0]


def get_merkle_proof(leaves: list[bytes], index: int) -> list[dict[str, str]]:
    """Generate a Merkle inclusion proof for the leaf at *index*.

    :param leaves: Pre-hashed leaf values used to build the tree.
    :param index: 0-based index of the leaf to prove.
    :returns: Ordered list of sibling hashes, each as::

            {"hash": "<64-char hex>", "direction": "left" | "right"}

        where ``"direction"`` is the side of the *sibling* relative to the
        current node.  To recompute the parent:

        * ``direction == "right"`` → parent = SHA-256(current || sibling)
        * ``direction == "left"``  → parent = SHA-256(sibling || current)

    :raises IndexError: If *index* is out of range.
    :raises ValueError: If *leaves* is empty.
    """
    if not leaves:
        raise ValueError("Cannot generate proof for an empty leaf list")
    if index < 0 or index >= len(leaves):
        raise IndexError(f"Leaf index {index} out of range [0, {len(leaves)})")

    levels = build_merkle_tree(leaves)
    proof: list[dict[str, str]] = []
    current_index = index

    for level in levels[:-1]:  # skip root level
        # Pad to even length (mirrors build_merkle_tree)
        if len(level) % 2 == 1:
            level = level + [level[-1]]

        if current_index % 2 == 0:
            # current is left child; sibling is to the right
            sibling_index = current_index + 1
            direction = "right"
        else:
            # current is right child; sibling is to the left
            sibling_index = current_index - 1
            direction = "left"

        proof.append({"hash": level[sibling_index].hex(), "direction": direction})
        current_index //= 2

    return proof


def verify_merkle_proof(
    leaf: bytes,
    proof: list[dict[str, str]],
    root: bytes,
) -> bool:
    """Verify a Merkle inclusion proof.

    Traverses *proof* from *leaf* toward the root, computing parent hashes at
    each step.  Returns ``True`` only if the final computed hash equals *root*
    exactly.  Any tampered leaf, proof node, or root causes ``False``.

    :param leaf: The 32-byte leaf hash to verify.
    :param proof: Ordered sibling list as returned by :func:`get_merkle_proof`.
    :param root: Expected 32-byte Merkle root.
    :returns: ``True`` if verified; ``False`` otherwise.
    """
    current = leaf
    for step in proof:
        sibling = bytes.fromhex(step["hash"])
        if step["direction"] == "right":
            current = _sha256(current + sibling)
        else:
            current = _sha256(sibling + current)
    return current == root


# ---------------------------------------------------------------------------
# Certificate proof (combined chain + Merkle)
# ---------------------------------------------------------------------------


def get_certificate_proof(
    db: sqlite3.Connection,
    cert_id: str,
) -> dict[str, object]:
    """Return a combined chain-hash + Merkle proof bundle for *cert_id*.

    Fetches **all** certificates from the database (ordered by ``minted_at``,
    ``id`` ascending), builds a Merkle tree over their leaf hashes, and
    generates a Merkle proof for the requested certificate.  The ``valid``
    field is ``True`` only when:

    * The certificate exists.
    * Its Merkle proof verifies against the computed root.

    Returned structure::

        {
            "certificate_id": str,
            "leaf_hash":      "<64-char hex>",    # SHA-256(certificate_bytes)
            "proof":          list[dict],          # from get_merkle_proof
            "merkle_root":    "<64-char hex>",
            "chain_hash":     "<64-char hex>",     # stored ledger_hash_hex
            "valid":          bool,
        }

    :param db: An open SQLite connection with the VERITAS schema.
    :param cert_id: Primary key of the certificate to prove.
    :returns: Proof bundle dict as described above.
    :raises sqlite3.OperationalError: If *cert_id* is not found in the DB.
    """
    db.row_factory = sqlite3.Row
    cur = db.cursor()

    # Fetch all certs in deterministic order
    cur.execute(
        "SELECT id, arrival_id, facility_id, quantity_kg, waste_category, "
        "minted_at, ledger_hash_hex "
        "FROM certificates "
        "ORDER BY minted_at ASC, id ASC"
    )
    all_rows = cur.fetchall()

    if not all_rows:
        raise sqlite3.OperationalError(f"Certificate not found: {cert_id!r}")

    # Build ordered list of cert dicts and locate the target
    all_certs: list[dict[str, object]] = [dict(r) for r in all_rows]
    target_index: Optional[int] = None
    for i, c in enumerate(all_certs):
        if c["id"] == cert_id:
            target_index = i
            break

    if target_index is None:
        raise sqlite3.OperationalError(f"Certificate not found: {cert_id!r}")

    target = all_certs[target_index]

    # Leaf hashes = SHA-256(certificate_bytes) for each cert
    leaf_hashes: list[bytes] = [_sha256(certificate_bytes(c)) for c in all_certs]
    target_leaf = leaf_hashes[target_index]

    # Build Merkle tree and proof
    root = get_merkle_root(leaf_hashes)
    proof = get_merkle_proof(leaf_hashes, target_index)
    proof_valid = verify_merkle_proof(target_leaf, proof, root)

    # Also verify the stored chain hash matches the recomputed value.
    # The Merkle proof only covers certificate_bytes() (which excludes
    # ledger_hash_hex), so a corrupted chain hash would pass the Merkle
    # check undetected.  We recompute from the predecessor's hash here.
    if target_index == 0:
        prev_hash_bytes: bytes = _GENESIS_HASH
    else:
        prev_stored = str(all_certs[target_index - 1].get("ledger_hash_hex", ""))
        if prev_stored in ("", None):
            prev_hash_bytes = _GENESIS_HASH
        else:
            prev_hash_bytes = bytes.fromhex(prev_stored)

    expected_chain_hash = hash_chain_entry(prev_hash_bytes, target)
    stored_chain_hash = str(target.get("ledger_hash_hex", ""))
    chain_hash_valid = stored_chain_hash == expected_chain_hash.hex()

    return {
        "certificate_id": cert_id,
        "leaf_hash": target_leaf.hex(),
        "proof": proof,
        "merkle_root": root.hex(),
        "chain_hash": stored_chain_hash,
        "valid": proof_valid and chain_hash_valid,
    }
